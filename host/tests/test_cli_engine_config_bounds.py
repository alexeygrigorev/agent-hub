"""Codex/ZAI config.toml uses one finite 1 MiB read/write bound (synthetic homes only).

Collected by the required ``test_cli*.py`` CI selection. No real profile, provider
or credential is touched: every managed home is a temporary directory.
"""
import os
import stat
import tempfile
import tomllib
import unittest
from pathlib import Path
from unittest import mock

from agent_hub_host import private_fs
from agent_hub_host import provisioning as p

OLD_LIMIT = 131072
NEW_LIMIT = 1048576
SETTINGS = 'model = "gpt-synthetic"\n[profiles.keep]\nname = "unrelated"\n'
SETTING_DOC = {'model': 'gpt-synthetic', 'profiles': {'keep': {'name': 'unrelated'}}}


def _padded(target_bytes, text=SETTINGS, filler='# pad\n'):
    """Valid TOML of exactly ``target_bytes`` UTF-8 bytes (filler is ASCII comments)."""
    head = text.encode()
    pad = target_bytes - len(head)
    assert pad >= 0
    body = (filler * (pad // len(filler) + 1)).encode()[:pad]
    # Keep the file valid TOML: trailing partial comment lines are still comments.
    return head + body


class EngineConfigBoundTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR') or None)
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.home = root / 'home'
        for name in ('.codex', '.zcodex', '.claude'):
            (self.home / name).mkdir(parents=True, mode=0o700)
        env = mock.patch.dict(os.environ, {'HOME': str(self.home)})
        env.start()
        self.addCleanup(env.stop)

    def path(self, provider='codex'):
        return self.home / ('.codex' if provider == 'codex' else '.zcodex') / 'config.toml'

    def install(self, provider='codex'):
        p.install_managed_engine_permissions({'provider': provider}, self.home, trusted_paths=['/w/synthetic'])

    def put(self, provider, raw, mode=0o600):
        path = self.path(provider)
        path.write_bytes(raw)
        os.chmod(path, mode)
        return path

    def assert_untouched(self, path, raw):
        self.assertEqual(path.read_bytes(), raw)

    # -- causal control: accepted input near 128 KiB plus authorized growth ----------
    def test_near_old_limit_input_with_growth_old_bound_fails_new_passes(self):
        raw = _padded(131050)
        for provider in ('codex', 'zai'):
            with self.subTest(provider=provider):
                path = self.put(provider, raw)
                self.assertLessEqual(len(raw), OLD_LIMIT)
                self.install(provider)
                out = path.read_bytes()
                self.assertGreater(len(out), OLD_LIMIT)
                self.assertLessEqual(len(out), NEW_LIMIT)
                doc = tomllib.loads(out.decode())
                for key, value in SETTING_DOC.items():
                    self.assertEqual(doc[key], value)
                self.assertEqual(doc['approval_policy'], 'never')
                self.assertIs(doc['check_for_update_on_startup'], False)
                self.assertEqual(doc['projects']['/w/synthetic']['trust_level'], 'trusted')
                # The same generated bytes under the previous shared bound are refused.
                with self.assertRaises(ValueError):
                    private_fs.atomic_write(path, out, OLD_LIMIT, engine_owned=True)
                with self.assertRaises(ValueError):
                    p._write_engine_config(path, out, None)

    def test_repeat_install_is_noop_and_keeps_inode(self):
        path = self.put('codex', _padded(131050))
        self.install()
        before = (path.read_bytes(), path.stat().st_ino)
        self.install()
        self.assertEqual((path.read_bytes(), path.stat().st_ino), before)

    # -- byte (not character) boundaries ----------------------------------------------
    def test_input_exactly_at_bound_is_read_and_one_over_is_refused(self):
        ok = _padded(NEW_LIMIT)
        path = self.put('codex', ok)
        self.assertEqual(p._engine_toml_config(path)[0], ok)
        path = self.put('codex', _padded(NEW_LIMIT + 1))
        before = path.stat().st_ino
        with self.assertRaises(p.EngineTomlConfigError):
            p._engine_toml_config(path)
        self.assertEqual(path.stat().st_ino, before)

    def test_non_ascii_counts_encoded_bytes(self):
        text = '# é中\n' * 3  # 2- and 3-byte characters
        base = 'model = "m"\n'
        unit = '# é中\n'
        n_bytes = len(unit.encode())
        self.assertGreater(n_bytes, len(unit))
        count = (NEW_LIMIT - len(base.encode())) // n_bytes
        raw = (base + unit * count).encode()
        slack = NEW_LIMIT - len(raw)
        raw += b'#' * slack  # exactly NEW_LIMIT bytes, far fewer characters
        self.assertEqual(len(raw), NEW_LIMIT)
        self.assertLess(len(raw.decode()), NEW_LIMIT)
        self.assertEqual(p._engine_toml_config(self.put('codex', raw))[0], raw)
        over = raw + b'#'
        with self.assertRaises(p.EngineTomlConfigError):
            p._engine_toml_config(self.put('codex', over))
        del text

    def test_generated_output_over_bound_refuses_before_publication(self):
        # Input exactly at the bound: authorized growth must not publish a truncated file.
        raw = _padded(NEW_LIMIT)
        for provider in ('codex', 'zai'):
            with self.subTest(provider=provider):
                path = self.put(provider, raw)
                ino = path.stat().st_ino
                with mock.patch.object(private_fs, 'atomic_write') as write:
                    with self.assertRaises(p.EngineTomlConfigError):
                        self.install(provider)
                    write.assert_not_called()
                self.assert_untouched(path, raw)
                self.assertEqual(path.stat().st_ino, ino)
                leftovers = [x.name for x in path.parent.iterdir() if x.name.endswith('.tmp')]
                self.assertEqual(leftovers, [])

    # -- refusal without loss ---------------------------------------------------------
    def test_oversized_existing_input_refused_without_empty_defaults(self):
        raw = _padded(NEW_LIMIT + 5)
        for provider in ('codex', 'zai'):
            with self.subTest(provider=provider):
                path = self.put(provider, raw)
                ino = path.stat().st_ino
                with mock.patch.object(private_fs, 'atomic_write') as write:
                    with self.assertRaises(p.EngineTomlConfigError) as ctx:
                        self.install(provider)
                    write.assert_not_called()
                self.assert_untouched(path, raw)
                self.assertEqual(path.stat().st_ino, ino)
                self.assertNotIn('gpt-synthetic', str(ctx.exception))
                self.assertNotIn(str(self.home), str(ctx.exception))

    def test_invalid_utf8_refused_without_empty_defaults(self):
        raw = SETTINGS.encode() + b'# \xff\xfe broken\n'
        for provider in ('codex', 'zai'):
            with self.subTest(provider=provider):
                path = self.put(provider, raw)
                ino = path.stat().st_ino
                with mock.patch.object(private_fs, 'atomic_write') as write:
                    with self.assertRaises(p.EngineTomlConfigError):
                        self.install(provider)
                    write.assert_not_called()
                self.assert_untouched(path, raw)
                self.assertEqual(path.stat().st_ino, ino)

    def test_world_readable_input_may_tighten_but_content_is_kept(self):
        raw = _padded(NEW_LIMIT + 1)
        path = self.put('codex', raw, mode=0o644)
        ino = path.stat().st_ino
        with self.assertRaises(p.EngineTomlConfigError):
            self.install()
        self.assert_untouched(path, raw)
        self.assertEqual(path.stat().st_ino, ino)
        # Established 0644 -> 0600 repair may already have happened; never wider.
        self.assertEqual(stat.S_IMODE(path.stat().st_mode) & 0o077, 0)

    def test_world_readable_valid_config_is_tightened_and_published_private(self):
        path = self.put('codex', SETTINGS.encode(), mode=0o644)
        self.install()
        self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o600)
        self.assertEqual(tomllib.loads(path.read_text())['profiles'], SETTING_DOC['profiles'])

    def test_absent_file_starts_empty_and_is_created_privately(self):
        for provider in ('codex', 'zai'):
            with self.subTest(provider=provider):
                path = self.path(provider)
                self.assertFalse(path.exists())
                self.install(provider)
                self.assertEqual(stat.S_IMODE(path.stat().st_mode), 0o600)
                doc = tomllib.loads(path.read_text())
                self.assertEqual(doc['sandbox_mode'], 'danger-full-access')
                self.assertEqual(doc['projects']['/w/synthetic']['trust_level'], 'trusted')

    # -- scope: nothing else widened --------------------------------------------------
    def test_other_bounds_are_unchanged(self):
        self.assertEqual(p.ENGINE_TOML_MAX_BYTES, NEW_LIMIT)
        raw = b'x' * (OLD_LIMIT + 1)
        path = self.home / '.codex' / 'other.json'
        path.write_bytes(raw)
        os.chmod(path, 0o600)
        with self.assertRaises(ValueError):  # generic reader default stays 128 KiB
            p.read_engine_file(path)
        with self.assertRaises(ValueError):
            private_fs.read_bytes(path, OLD_LIMIT)
        with self.assertRaises(ValueError):
            private_fs.atomic_write(self.home / '.codex' / 'w', raw, OLD_LIMIT)

    def test_claude_json_oversize_still_falls_back_to_defaults_at_old_bound(self):
        settings = self.home / '.claude' / 'settings.json'
        settings.write_bytes(b'{"k": "' + b'a' * OLD_LIMIT + b'"}')
        os.chmod(settings, 0o600)
        with mock.patch.object(p.hook_command, 'tool_command', lambda name: '/usr/bin/a'):
            p.install_managed_engine_permissions({'provider': 'claude'}, self.home, trusted_paths=['/w'])
        self.assertNotIn('"k"', settings.read_text())  # unchanged legacy JSON behavior

    def test_hooks_reader_bound_is_unchanged(self):
        hooks = self.home / '.codex' / 'hooks.json'
        hooks.write_bytes(b' ' * (OLD_LIMIT + 1))
        os.chmod(hooks, 0o600)
        self.put('codex', SETTINGS.encode())
        self.install()  # oversized hooks are ignored exactly as before, config still written
        self.assertEqual(tomllib.loads(self.path().read_text())['model'], 'gpt-synthetic')
        with self.assertRaises(ValueError):
            p.read_engine_file(hooks)


if __name__ == '__main__':
    unittest.main()
